-- ===============================================================
-- Supabase Setup Script (Bita AI Training Data & Messages)
-- ===============================================================
-- Is pure code ko Supabase Dashboard -> "SQL Editor" me paste karein aur "RUN" dabayein:

-- 1. Create 'training_data' table (Har sawal-jawab auto-save ke liye)
CREATE TABLE IF NOT EXISTS public.training_data (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  instruction TEXT NOT NULL,  -- User ka sawal
  output TEXT NOT NULL,       -- AI ka jawab
  tag TEXT DEFAULT 'Auto'
);

-- 2. Create 'messages' table (Chat history ke liye)
CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
  role TEXT NOT NULL,         -- 'user' ya 'assistant'
  content TEXT NOT NULL
);

-- 3. Enable Realtime Replication
ALTER PUBLICATION supabase_realtime ADD TABLE training_data;
ALTER PUBLICATION supabase_realtime ADD TABLE messages;

-- 4. Disable Row Level Security (RLS) - Taaki Frontend aur Backend se direct INSERT ho sake bina kisi rukawat ke:
ALTER TABLE public.training_data DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages DISABLE ROW LEVEL SECURITY;

